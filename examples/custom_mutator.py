#!/usr/bin/env python3
"""Example showing how to create a domain-specific mutator.

This can be used to target unique business logic in your API such as
billing, user permissions, or file uploads.
"""

from __future__ import annotations

import json
from typing import Optional

from rich.console import Console
from rich.panel import Panel

from fuzzforge.core import FuzzForge, TestCase
from fuzzforge.mutators import Mutator


class PaymentTamperingMutator(Mutator):
    """Mutator focused on e-commerce / payment endpoint weaknesses.

    Common issues: negative amounts, currency confusion, zero-value
    transactions, tax manipulation.
    """

    name: str = "payment_tampering"
    description: str = "Targets payment logic flaws and tampering vectors"

    def apply(self, test: TestCase) -> Optional[TestCase]:
        """Only mutate tests that appear to be related to payments or transactions."""
        payload_str = json.dumps(test.payload).lower() if test.payload else ""
        if not any(
            kw in payload_str
            for kw in ("amount", "price", "total", "payment", "bill")
        ) and "payment" not in "".join(test.tags).lower():
            return None

        mutated = test.model_copy(deep=True)
        mutated.tags.extend(["payment_tampering", "business_logic"])
        # Remove duplicates while preserving order
        mutated.tags = list(dict.fromkeys(mutated.tags))

        payload = dict(mutated.payload or {})

        # Tamper with monetary values
        for key in list(payload.keys()):
            if any(
                monetary in key.lower() for monetary in ("amount", "price", "total", "value")
            ):
                payload[key] = -9999.99
                break
        else:
            payload["amount"] = 0
            payload["currency"] = "TEST"
            payload["tax_rate"] = 999

        mutated.payload = payload
        mutated.description = (
            "Payment tampering: negative amount, invalid currency, extreme tax"
        )
        mutated.risk_potential = "critical"
        mutated.query_params["bypass"] = "1"
        return mutated


if __name__ == "__main__":
    console = Console()
    console.print(Panel(
        "CUSTOM MUTATOR DEMO\n"
        "Showing PaymentTamperingMutator",
        title="Fuzz Forge",
        border_style="#ff0044",
        style="#ffff00",
    ))

    # Base test that would be generated by LLM for a payment endpoint
    base = TestCase(
        endpoint="POST /checkout",
        method="POST",
        path="/checkout",
        payload={
            "user_id": "usr_123",
            "amount": 49.99,
            "currency": "USD",
            "item": "premium_plan",
        },
        tags=["payment"],
        description="Process checkout transaction",
    )

    mutator = PaymentTamperingMutator()
    result = mutator.apply(base)

    if result:
        console.print("Base test payload :", base.payload, style="#ffff00")
        console.print("Mutated payload   :", result.payload, style="#ff0044")
        console.print(
            "Added tags        :",
            [t for t in result.tags if any(x in t for x in ("tampering", "logic"))],
            style="#ffff00",
        )
        console.print("New risk level    :", result.risk_potential, style="#ff0044")

    console.print("\n[dim]This mutator can be added to any FuzzForge instance by appending to "
                 "mutator_instances after initialisation.[/dim]")
