"""Core models and orchestrator for Fuzz Forge.

Defines the data models (APISpec, TestCase, TestResult) and the main
FuzzForge class that coordinates parsing, LLM generation, mutation,
and execution of security tests. Now supports GraphQL schemas.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, model_validator


class APISpec(BaseModel):
    """Parsed API specification (OpenAPI or GraphQL) with semantic context for test generation."""

    title: str = "Untitled API"
    version: str = "1.0.0"
    endpoints: List[Dict[str, Any]] = Field(default_factory=list)
    schemas: Dict[str, Any] = Field(default_factory=dict)
    security_schemes: Dict[str, Any] = Field(default_factory=dict)
    servers: List[str] = Field(default_factory=lambda: ["http://localhost:8000"])
    raw_spec: Dict[str, Any] = Field(default_factory=dict)
    spec_type: str = Field(default="openapi", pattern="^(openapi|graphql)$")

    @model_validator(mode="after")
    def validate_endpoints(self) -> APISpec:
        """Ensure at least minimal endpoint data is present."""
        if not self.endpoints:
            raise ValueError("Spec must contain at least one endpoint")
        return self

    __test__ = False


class TestCase(BaseModel):
    """A single security test case generated by LLM and refined by mutators.

    Contains all information needed to execute the test and reproduce it later.
    """

    id: str = Field(default_factory=lambda: f"tc_{__import__('time').time():.0f}")
    method: str = Field(default="GET", pattern="^(GET|POST|PUT|DELETE|PATCH|OPTIONS)$")
    path: str = Field(default="/")
    endpoint: str = Field(..., description="Human-readable endpoint label e.g. 'GET /pets/{id}'")
    payload: Dict[str, Any] = Field(default_factory=dict)
    query_params: Dict[str, Any] = Field(default_factory=dict)
    headers: Dict[str, Any] = Field(default_factory=dict)
    tags: List[str] = Field(default_factory=list)
    description: str = ""
    expected_behavior: str = "Should reject malicious input or reveal logic flaw"
    risk_potential: str = Field(default="medium", pattern="^(low|medium|high|critical)$")
    security: Dict[str, Any] = Field(default_factory=dict)

    def to_curl(self, base_url: str = "http://localhost:8000") -> str:
        """Return a ready-to-run curl command reproducing this test case.

        Args:
            base_url: Base URL to use for the request.

        Returns:
            Complete curl command string.
        """
        url = f"{base_url.rstrip('/')}{self.path}"
        if self.query_params:
            qs = "&".join(f"{k}={v}" for k, v in self.query_params.items())
            url = f"{url}?{qs}"

        cmd = [f"curl -X {self.method} '{url}'"]
        for k, v in self.headers.items():
            cmd.append(f"-H '{k}: {v}'")
        if self.payload:
            payload_str = json.dumps(self.payload, separators=(",", ":"))
            cmd.append(f"-d '{payload_str}'")
        return " ".join(cmd)

    model_config = {"extra": "forbid"}
    __test__ = False


class TestResult(BaseModel):
    """Result of executing one TestCase against a live (or dry-run) target."""

    test_case: TestCase
    executed: bool = False
    status_code: Optional[int] = None
    response_time: Optional[float] = None
    response_body: Optional[str] = None
    error: Optional[str] = None
    risk_score: int = Field(default=0, ge=0, le=10)
    findings: List[str] = Field(default_factory=list)
    repro_curl: str = ""

    @property
    def is_vulnerable(self) -> bool:
        """Heuristic: scores above 5 are considered potential findings."""
        return self.risk_score > 5

    model_config = {"extra": "forbid"}
    __test__ = False


class FuzzForge:
    """Main entrypoint for loading specs, generating tests, and running them.

    Maintains safe defaults (dry-run, host allowlist, rate limiting).
    Supports first-class OAuth2, API-key, and GraphQL schemas with mutation generation.
    """

    def __init__(
        self,
        model: str = "llama3.2",
        mutators: Optional[List[str]] = None,
        dry_run: bool = True,
        output_dir: Optional[str] = "fuzz-reports",
        rate_limit_rps: float = 5.0,
        allowed_hosts: Optional[List[str]] = None,
        api_key: Optional[str] = None,
        bearer_token: Optional[str] = None,
        auto_detect_rate_limits: bool = True,
    ) -> None:
        """Initialize with safe, production-ready defaults.

        Args:
            model: Ollama model name (must be available locally).
            mutators: List of mutator names or ["all"].
            dry_run: When True, no HTTP requests are sent.
            output_dir: Directory for reports and repro artifacts.
            rate_limit_rps: Maximum requests per second (enforced by executor).
            allowed_hosts: Hostnames allowed for real HTTP execution.
            api_key: Credential for apiKey schemes.
            bearer_token: Credential for OAuth2 / Bearer schemes.
            auto_detect_rate_limits: Whether to parse rate-limit headers and
                dynamically back off.

        Raises:
            ValueError: On invalid configuration values.
        """
        if not model or not isinstance(model, str):
            raise ValueError("model must be a non-empty string")
        if mutators is not None and not isinstance(mutators, list):
            raise ValueError("mutators must be a list of strings or None")

        self.model = model
        self.mutators = mutators or ["all"]
        self.dry_run = dry_run
        self.output_dir = output_dir or "fuzz-reports"
        self.rate_limit_rps = max(0.5, float(rate_limit_rps))
        self.allowed_hosts = allowed_hosts or ["localhost", "127.0.0.1", "example.com"]
        self.api_key = api_key
        self.bearer_token = bearer_token
        self.auto_detect_rate_limits = bool(auto_detect_rate_limits)
        self.spec: Optional[APISpec] = None
        self._test_cases: List[TestCase] = []

        self._initialize_components()

    def _initialize_components(self) -> None:
        """Lazy import components to avoid circular imports."""
        from .llm import LLMClient
        from .mutators import get_mutators, Mutator

        self.llm_client = LLMClient(model=self.model)
        self.mutator_instances: List[Mutator] = get_mutators(self.mutators)

    def from_spec(self, spec_path: str) -> None:
        """Parse an OpenAPI or GraphQL file into an APISpec.

        Args:
            spec_path: Filesystem path to OpenAPI YAML/JSON or GraphQL SDL.

        Raises:
            FileNotFoundError: If the file does not exist.
            ValueError: If the spec is invalid or empty.
        """
        path = Path(spec_path)
        if not path.is_file():
            raise FileNotFoundError(f"OpenAPI/GraphQL spec not found: {spec_path}")

        from .parser import OpenAPIParser

        parser = OpenAPIParser()
        self.spec = parser.parse(str(path))

    def generate(self, limit: int = 20) -> List[TestCase]:
        """Generate contextual security test cases via LLM + mutators.

        Args:
            limit: Maximum number of test cases to return.

        Returns:
            List of TestCase objects ready for execution.

        Raises:
            RuntimeError: If no spec has been loaded.
            ValueError: If limit is invalid.
        """
        if self.spec is None:
            raise RuntimeError("No spec loaded. Call from_spec() before generate().")

        if limit < 1:
            raise ValueError("limit must be at least 1")

        base_tests = self.llm_client.generate_tests(self.spec, count=min(limit, 12))

        if not base_tests:
            base_tests = self._generate_fallback_tests(limit)

        expanded: List[TestCase] = []
        for base in base_tests:
            expanded.append(base)
            for mutator in self.mutator_instances:
                try:
                    mutated = mutator.apply(base.model_copy(deep=True))
                    if mutated is not None:
                        # Avoid exact duplicate payloads
                        if not any(
                            t.payload == mutated.payload and t.path == mutated.path
                            for t in expanded
                        ):
                            expanded.append(mutated)
                except Exception:  # noqa: BLE001 - one bad mutator should not fail all
                    continue

        self._test_cases = expanded[:limit]
        return self._test_cases

    def _generate_fallback_tests(self, limit: int) -> List[TestCase]:
        """Return minimal viable tests when LLM is unavailable."""
        if not self.spec or not self.spec.endpoints:
            return []

        spec_type = getattr(self.spec, "spec_type", "openapi")
        tests: List[TestCase] = []

        if spec_type == "graphql":
            for _ in range(min(limit, 4)):
                tests.append(
                    TestCase(
                        endpoint="POST /graphql [mutation]",
                        method="POST",
                        path="/graphql",
                        payload={
                            "query": 'mutation { test(input: {malicious: "<script>alert(1)</script>"}) { id } }'
                        },
                        headers={"Content-Type": "application/json"},
                        tags=["graphql", "mutation", "injection", "fallback"],
                        description="Fallback GraphQL mutation test (LLM unavailable)",
                        risk_potential="high",
                        security={},
                    )
                )
            return tests

        for ep in self.spec.endpoints[:limit]:
            method = ep.get("method", "GET")
            path = ep.get("path", "/")
            tests.append(
                TestCase(
                    endpoint=f"{method} {path}",
                    method=method,
                    path=path,
                    payload=ep.get("example", {}),
                    tags=["fallback"],
                    description="Fallback test (LLM unavailable)",
                    risk_potential="medium",
                    security={},  # ensure dict (OpenAPI security can be a list)
                )
            )
        return tests

    def run(self, tests: Optional[List[TestCase]] = None) -> List[TestResult]:
        """Execute tests (or dry-run) and return enriched results.

        Args:
            tests: Optional explicit list; otherwise uses last generated tests.

        Returns:
            List of TestResult with risk scores and repro steps.
        """
        if tests is None:
            tests = self._test_cases
        if not tests:
            return []

        from .executor import TestExecutor

        executor = TestExecutor(
            dry_run=self.dry_run,
            rate_limit_rps=self.rate_limit_rps,
            allowed_hosts=self.allowed_hosts,
            security_schemes=self.spec.security_schemes if self.spec is not None else {},
            api_key=self.api_key,
            bearer_token=self.bearer_token,
            auto_detect_rate_limits=self.auto_detect_rate_limits,
        )
        results = executor.run_all(tests)

        base_url = (
            self.spec.servers[0] if self.spec is not None and self.spec.servers else "http://localhost:8000"
        )

        for result in results:
            if not result.repro_curl:
                result.repro_curl = result.test_case.to_curl(base_url=base_url)

            # Contextual risk scoring
            tags = [t.lower() for t in result.test_case.tags]
            if any(x in tags for x in ("auth_bypass", "critical")):
                result.risk_score = 9
                result.findings.append("Possible authentication bypass")
            elif any(x in tags for x in ("injection", "xss", "sqli")):
                result.risk_score = 7
                result.findings.append("Injection vector detected")
            elif "logic" in tags:
                result.risk_score = 6
                result.findings.append("Potential business-logic flaw")
            elif "graphql" in tags and "mutation" in tags:
                result.risk_score = 8
                result.findings.append("GraphQL mutation attack vector")

        return results


